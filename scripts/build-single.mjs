// Builds dist/worker-single.js: one file with the site pages inlined,
// for pasting into the Cloudflare dashboard editor (no Wrangler needed).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const vocab = readFileSync('src/vocab.js', 'utf8').replace(/^export \{[^}]*\};?\s*$/m, '');
let worker = readFileSync('src/worker.js', 'utf8').replace(/^import \{ BASE_VOCAB, TOPICS \} from '\.\/vocab\.js';\s*$/m, '');
const pages = {
  '/': ['text/html; charset=utf-8', readFileSync('public/index.html', 'utf8')],
  '/index.html': ['text/html; charset=utf-8', readFileSync('public/index.html', 'utf8')],
  '/feed.html': ['text/html; charset=utf-8', readFileSync('public/feed.html', 'utf8')],
  '/NOTICE.txt': ['text/plain; charset=utf-8', readFileSync('NOTICE', 'utf8')],
  '/skill.md': ['text/markdown; charset=utf-8', readFileSync('public/skill.md', 'utf8')],
  '/favicon.svg': ['image/svg+xml', readFileSync('public/favicon.svg', 'utf8')],
  '/logo.svg': ['image/svg+xml', readFileSync('public/logo.svg', 'utf8')],
  '/had-logo.png': ['image/png', readFileSync('public/had-logo.png').toString('base64'), 'b64'],
  '/apple-touch-icon.png': ['image/png', readFileSync('public/apple-touch-icon.png').toString('base64'), 'b64'],
  '/constitution.md': ['text/markdown; charset=utf-8', readFileSync('public/constitution.md', 'utf8')],
};
const assets = `
const PAGES = ${JSON.stringify(pages)};
const INLINE_ASSETS = { fetch(req) {
  const p = new URL(req.url).pathname; const f = PAGES[p];
  if (!f) return new Response('not found', { status: 404 });
  const body = f[2] === 'b64' ? Uint8Array.from(atob(f[1]), (c) => c.charCodeAt(0)) : f[1];
  return new Response(body, { headers: { 'content-type': f[0], 'cache-control': 'public, max-age=300' } });
} };
`;
worker = worker.replace('if (env.ASSETS) return env.ASSETS.fetch(req);', 'return (env.ASSETS || INLINE_ASSETS).fetch(req);');
mkdirSync('dist', { recursive: true });
writeFileSync('dist/worker-single.js', '// Hivetongue — single-file build. Generated by scripts/build-single.mjs\n' + vocab + assets + worker);
console.log('dist/worker-single.js', Buffer.byteLength(readFileSync('dist/worker-single.js')), 'bytes');
