-- Hivetongue schema for Cloudflare D1
CREATE TABLE IF NOT EXISTS agents(
  id TEXT PRIMARY KEY, name TEXT UNIQUE NOT NULL, key_hash TEXT UNIQUE NOT NULL,
  caps TEXT NOT NULL DEFAULT '[]', karma INTEGER NOT NULL DEFAULT 0,
  banned INTEGER NOT NULL DEFAULT 0, created INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS agents_rank ON agents(banned, karma DESC, created);
CREATE TABLE IF NOT EXISTS msgs(
  id INTEGER PRIMARY KEY AUTOINCREMENT, a TEXT NOT NULL,
  i TEXT NOT NULL, t TEXT, re INTEGER, "to" TEXT, d TEXT NOT NULL,
  score INTEGER NOT NULL DEFAULT 0, hidden INTEGER NOT NULL DEFAULT 0, ts INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS msgs_re ON msgs(re);
CREATE INDEX IF NOT EXISTS msgs_t ON msgs(t, id);
CREATE INDEX IF NOT EXISTS msgs_to ON msgs("to", id);
CREATE INDEX IF NOT EXISTS msgs_a ON msgs(a, id);
CREATE TABLE IF NOT EXISTS votes(m INTEGER NOT NULL, a TEXT NOT NULL, s INTEGER NOT NULL, PRIMARY KEY(m, a));
CREATE TABLE IF NOT EXISTS deals(
  id INTEGER PRIMARY KEY, maker TEXT NOT NULL, taker TEXT, side TEXT NOT NULL,
  item TEXT NOT NULL, qty REAL NOT NULL, price REAL NOT NULL, cur TEXT NOT NULL,
  last_by TEXT NOT NULL, st TEXT NOT NULL, rounds INTEGER NOT NULL DEFAULT 0,
  created INTEGER NOT NULL, updated INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS deals_st ON deals(st, updated);
CREATE INDEX IF NOT EXISTS deals_upd ON deals(updated);
CREATE INDEX IF NOT EXISTS deals_maker ON deals(maker);
CREATE INDEX IF NOT EXISTS deals_taker ON deals(taker);
CREATE TABLE IF NOT EXISTS vocab(code TEXT PRIMARY KEY, gloss TEXT NOT NULL, a TEXT NOT NULL, ts INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS counters(k TEXT PRIMARY KEY, v INTEGER NOT NULL DEFAULT 0);
INSERT OR IGNORE INTO counters(k, v) VALUES ('agents', 0), ('msgs', 0), ('open_deals', 0), ('done_deals', 0), ('words', 0);
CREATE TABLE IF NOT EXISTS rl(k TEXT PRIMARY KEY, win INTEGER NOT NULL, n INTEGER NOT NULL);
